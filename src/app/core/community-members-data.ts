import { Member } from '../shared/models/member.model';

const makeMember = (
  idNum: number,
  fullName: string,
  duesPeriod: string,
  startMonth: string,
  endMonthDate: string,
  isPending = false
): Member => {
  const numStr = idNum.toString().padStart(3, '0');
  const slug = fullName.toLowerCase().replace(/[^a-z0-9]/g, '');
  return {
    id: `mem-${numStr}`,
    memberNumber: `KM-2026-${numStr}`,
    fullName,
    email: `${slug}@komunika.id`,
    phone: `+62 8${(10 + (idNum % 89)).toString()}-${(1000 + idNum * 37).toString()}-${(2000 + idNum * 19).toString()}`,
    roleId: 'role-anggota',
    tier: idNum % 10 === 0 ? 'vip' : idNum % 5 === 0 ? 'pengurus' : 'reguler',
    status: isPending ? 'pending' : 'aktif',
    joinedAt: `2026-${startMonth}-01`,
    avatarUrl: `https://ui-avatars.com/api/?name=${encodeURIComponent(fullName)}&background=0d9488&color=fff&bold=true`,
    duesPaidUntil: endMonthDate,
    notes: duesPeriod ? `Iuran terbayar: ${duesPeriod} 2026` : 'Belum melunasi iuran',
    twoFactorActive: idNum % 3 === 0
  };
};

